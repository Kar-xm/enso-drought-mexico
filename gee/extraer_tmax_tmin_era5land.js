// 2. Máxima y mínima diarias de la temperatura a 2 m (Kelvin).
var diaria = ee.ImageCollection('ECMWF/ERA5_LAND/DAILY_AGGR')
  .select(['temperature_2m_max', 'temperature_2m_min']);

// 3. Promedio mensual de Tmax y Tmin diarias, muestreado en los puntos.
function tablaMes(t) {
  var ini = ee.Date(t);
  var fin = ini.advance(1, 'month');
  var mes = diaria.filterDate(ini, fin);
  var img = mes.mean().subtract(273.15).rename(['tmax_c', 'tmin_c']);   // Kelvin -> °C
  var nDias = mes.size();                                               // para verificar meses completos
  return img.reduceRegions({collection: puntos, reducer: ee.Reducer.first(), scale: 11132})
    .map(function (f) {
      return f.set({year: ini.get('year'), month: ini.get('month'), n_days: nDias});
    });
}

// Prueba rápida: junio de 2023 (revisa que tmax_c > tmin_c y valores razonables).
print('Prueba junio 2023 (primeros 5 puntos):', tablaMes(ee.Date('2023-06-01').millis()).limit(5));

// 4. Una exportación por bloque de años (como tus archivos ERA5_Mexico_*.csv).
var bloques = [[1950, 1969], [1970, 1989], [1990, 2009], [2010, 2024]];
bloques.forEach(function (b) {
  var nMeses = (b[1] - b[0] + 1) * 12;
  var meses = ee.List.sequence(0, nMeses - 1).map(function (k) {
    return ee.Date.fromYMD(b[0], 1, 1).advance(k, 'month').millis();
  });
  var tabla = ee.FeatureCollection(meses.map(tablaMes)).flatten();
  Export.table.toDrive({
    collection: tabla,
    description: 'ERA5L_TmaxTmin_' + b[0] + '_' + b[1],
    folder: 'GEE_ERA5_Tmax_Tmin',
    fileNamePrefix: 'ERA5L_TmaxTmin_' + b[0] + '_' + b[1],
    fileFormat: 'CSV',
    selectors: ['lon', 'lat', 'year', 'month', 'n_days', 'tmax_c', 'tmin_c']
  });
});
