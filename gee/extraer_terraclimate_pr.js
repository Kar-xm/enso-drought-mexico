var tc = ee.ImageCollection('IDAHO_EPSCOR/TERRACLIMATE').select('pr');

function tablaMes(t) {
  var ini = ee.Date(t);
  var img = tc.filterDate(ini, ini.advance(1, 'month')).first().rename('pr_mm');
  // Con una sola banda, reduceRegions nombra la salida como el reductor ("mean"):
  // setOutputs la renombra a pr_mm para que la columna no salga vacía.
  return img.reduceRegions({collection: puntos, reducer: ee.Reducer.mean().setOutputs(['pr_mm']), scale: 4638.3})
    .map(function (f) {
      return ee.Feature(null, f.toDictionary()).set({year: ini.get('year'), month: ini.get('month')});
    });
}
